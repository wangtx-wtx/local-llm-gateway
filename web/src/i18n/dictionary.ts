/**
 * Translation dictionary.
 *
 * Deliberately a plain object rather than an i18n framework: the dashboard ships
 * with zero runtime dependencies, and the whole app needs only a lookup and an
 * interpolation helper.
 *
 * Conventions:
 *  - Keys are grouped by the view that owns them (`nav.*`, `dashboard.*`, ...),
 *    so a missing translation points straight at the file to fix.
 *  - `common.*` holds shared vocabulary, `enum.*` holds labels for values that
 *    come from the API (key statuses, protocol modes, ...). Enum labels are the
 *    ONLY place API values are translated — raw values from the backend are
 *    never rewritten, only displayed with a localised label.
 *  - `{name}` placeholders are interpolated by `t()`.
 *  - Both languages must define exactly the same key set; `tests/unit/i18n.test.ts`
 *    fails the build otherwise.
 */

